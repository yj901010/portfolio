const node = (title: string, detail: string, step?: number): DiagramBlock => ({ type: "node", title, detail, step });
const flow = (...items: DiagramBlock[]): DiagramBlock => ({ type: "flow", items });
const split = (...items: DiagramBlock[]): DiagramBlock => ({ type: "split", items });

function implementation(
  id: string, label: string, title: string, context: string, outcome: string,
  steps: StoryStep[], problem: DiagramBlock[], solution: DiagramBlock[],
): ImplementationStory {
  return {
    id, label, title, context, outcome, steps, defaultView: 1,
    views: [{ title: "고려한 문제", blocks: problem }, { title: "구현 흐름", blocks: solution }],
  };
}

